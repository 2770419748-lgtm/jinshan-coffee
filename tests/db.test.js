// SQLite 文档数据库：查询条件、排序、更新的行为要和业务代码原来用的云数据库一致
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { Database } = require('../server/lib/db')

const db = new Database(':memory:')
const _ = db.command
const col = () => db.collection('things')

test('写进去什么读出来什么：日期还原成 Date，serverDate 是当前时间', async () => {
  db.reset()
  const before = Date.now()
  const { _id } = await col().add({ data: { name: '手冲', price: 3200, onShelf: true, tags: ['热', '冰'], meta: { a: 1 }, at: new Date('2026-01-02T03:04:05Z'), createdAt: db.serverDate() } })
  assert.match(_id, /^[0-9a-f]{32}$/)
  const doc = (await col().doc(_id).get()).data
  assert.equal(doc._id, _id)
  assert.deepEqual(doc.tags, ['热', '冰'])
  assert.deepEqual(doc.meta, { a: 1 })
  assert.ok(doc.at instanceof Date)
  assert.equal(doc.at.toISOString(), '2026-01-02T03:04:05.000Z')
  assert.ok(doc.createdAt instanceof Date && doc.createdAt.getTime() >= before)
})

test('查询条件：相等、布尔、in、大小比较、neq（字段不存在也算不等）', async () => {
  db.reset()
  await col().add({ data: { _id: 'a', n: 1, on: true, s: 'x', at: new Date('2026-01-01') } })
  await col().add({ data: { _id: 'b', n: 2, on: false, s: 'y', at: new Date('2026-03-01') } })
  await col().add({ data: { _id: 'c', n: 3, s: '1' } })
  const ids = async (where) => (await col().where(where).get()).data.map((d) => d._id).sort().join('')
  assert.equal(await ids({ on: true }), 'a')
  assert.equal(await ids({ on: false }), 'b')
  assert.equal(await ids({ n: 1 }), 'a', '数字 1 不等于 true')
  assert.equal(await ids({ s: '1' }), 'c')
  assert.equal(await ids({ s: 1 }), '', '字符串和数字不相等')
  assert.equal(await ids({ n: _.in([1, 3]) }), 'ac')
  assert.equal(await ids({ n: _.in([]) }), '')
  assert.equal(await ids({ _id: _.in(['b', 'c']) }), 'bc')
  assert.equal(await ids({ n: _.gt(1) }), 'bc')
  assert.equal(await ids({ n: _.gte(2), s: 'y' }), 'b')
  assert.equal(await ids({ n: _.lt(2) }), 'a')
  assert.equal(await ids({ at: _.lt(new Date('2026-02-01')) }), 'a', '日期可以比较')
  assert.equal(await ids({ on: _.neq(true) }), 'bc')
  assert.equal(await ids({ s: _.neq('x') }), 'bc')
  assert.equal((await col().where({ n: _.gt(1) }).count()).total, 2)
})

test('排序、分页、只取部分字段；同样大小的按写入顺序', async () => {
  db.reset()
  for (let i = 0; i < 5; i++) await col().add({ data: { _id: 'k' + i, sort: i % 2, at: new Date(2026, 0, 5 - i) } })
  const page = await col().orderBy('sort', 'asc').skip(1).limit(2).get()
  assert.deepEqual(page.data.map((d) => d._id), ['k2', 'k4'])
  const byDate = await col().orderBy('at', 'asc').limit(10).get()
  assert.deepEqual(byDate.data.map((d) => d._id), ['k4', 'k3', 'k2', 'k1', 'k0'])
  const two = await col().orderBy('sort', 'desc').orderBy('at', 'desc').field({ sort: true }).get()
  assert.deepEqual(two.data[0], { _id: 'k1', sort: 1 })
  await assert.rejects(col().limit(1001).get(), /limit too large/)
})

test('更新：带条件的更新只改符合的；_.inc、_.set、对象合并一层', async () => {
  db.reset()
  await col().add({ data: { _id: 'o', status: 'unpaid', count: 1, web: { salt: 's', hash: 'h', fails: 2 } } })
  const first = await col().where({ _id: 'o', status: 'unpaid' }).update({ data: { status: 'paid', paidAt: db.serverDate() } })
  const again = await col().where({ _id: 'o', status: 'unpaid' }).update({ data: { status: 'paid' } })
  assert.equal(first.stats.updated, 1)
  assert.equal(again.stats.updated, 0, '同一单不会被标两次')
  await col().doc('o').update({ data: { count: _.inc(2), web: { fails: 0 } } })
  let doc = (await col().doc('o').get()).data
  assert.equal(doc.count, 3)
  assert.deepEqual(doc.web, { salt: 's', hash: 'h', fails: 0 })
  assert.ok(doc.paidAt instanceof Date)
  await col().doc('o').update({ data: { web: _.set(null), list: ['a'] } })
  doc = (await col().doc('o').get()).data
  assert.equal(doc.web, null)
  assert.deepEqual(doc.list, ['a'])
  assert.equal((await col().doc('missing').update({ data: { a: 1 } })).stats.updated, 0)
  await assert.rejects(col().doc('o').update({ data: { _id: 'x' } }))
})

test('新建重复的 _id 报错；doc().get() 查不到报错；set 整条替换；删除', async () => {
  db.reset()
  await col().add({ data: { _id: 'x', a: 1 } })
  await assert.rejects(col().add({ data: { _id: 'x', a: 2 } }), /duplicate/)
  await assert.rejects(col().doc('nope').get(), /does not exist/)
  await col().doc('x').set({ data: { b: 2 } })
  assert.deepEqual((await col().doc('x').get()).data, { _id: 'x', b: 2 })
  await col().doc('y').set({ data: { c: 3 } })
  assert.equal((await col().count()).total, 2)
  assert.equal((await col().where({ c: 3 }).remove()).stats.removed, 1)
  assert.equal((await col().doc('x').remove()).stats.removed, 1)
  assert.equal((await col().count()).total, 0)
})

test('集合第一次用到时自动建好；集合名、字段名不合法直接报错', async () => {
  db.reset()
  assert.equal(db.hasCollection('fresh'), false)
  assert.deepEqual((await db.collection('fresh').get()).data, [])
  assert.equal(db.hasCollection('fresh'), true)
  await assert.rejects(db.collection('bad name; drop table x').get(), /bad collection name/)
  await assert.rejects(db.collection('ok').where({ "a') OR 1=1 --": 1 }).get(), /bad field/)
})

test('事务排队执行：并发取号不会重复', async () => {
  db.reset()
  await db.collection('counters').add({ data: { _id: 'c', seq: 0 } })
  const next = () => db.runTransaction(async (t) => {
    const res = await t.collection('counters').doc('c').get()
    await new Promise((r) => setTimeout(r, 1))
    await t.collection('counters').doc('c').update({ data: { seq: res.data.seq + 1 } })
    return res.data.seq + 1
  })
  const seqs = await Promise.all([next(), next(), next(), next()])
  assert.deepEqual(seqs.sort(), [1, 2, 3, 4])
  // 出错的事务不影响后面的
  await assert.rejects(db.runTransaction(async () => { throw new Error('boom') }))
  assert.equal(await next(), 5)
})

test('数据存在文件里，重开还在；备份出来的文件也能打开', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'jinshan-db-'))
  const file = path.join(dir, 'a.db')
  const a = new Database(file)
  await a.collection('staff').add({ data: { _id: 'OWNER', name: '坤总', createdAt: new Date('2026-10-25T00:00:00Z') } })
  a.backupTo(path.join(dir, 'backup.db'))
  a.close()
  const b = new Database(file)
  assert.equal((await b.collection('staff').doc('OWNER').get()).data.name, '坤总')
  b.close()
  const c = new Database(path.join(dir, 'backup.db'))
  assert.equal((await c.collection('staff').doc('OWNER').get()).data.createdAt.toISOString(), '2026-10-25T00:00:00.000Z')
  c.close()
  fs.rmSync(dir, { recursive: true, force: true })
})
